import assert from 'node:assert/strict'
import {chromium} from 'playwright-core'
const base=(process.env.BASE??'http://127.0.0.1:5174').replace(/\/$/,'')
const browser=await chromium.launch({channel:'chrome',headless:true})
try{
 const p=await browser.newPage({viewport:{width:390,height:844}}), errors=[]
 p.on('pageerror',e=>errors.push(e.message))
 await p.route('https://photon.komoot.io/**',r=>r.fulfill({json:{features:r.request().url().includes('/reverse')?[{geometry:{coordinates:[-122.4001,37.7801]},properties:{osm_type:'N',osm_id:1,osm_key:'amenity',osm_value:'cafe',name:'Fixture Coffee'}}]:[{geometry:{coordinates:[-122.4,37.78]},properties:{name:'San Francisco',country:'United States'}}]}}))
 await p.route('https://www.openstreetmap.org/api/**',r=>r.fulfill({json:{elements:[{type:'node',id:1,tags:{name:'Fixture Coffee',amenity:'cafe','diet:vegetarian':'yes'}}]}}))
 await p.goto(`${base}/#/tasks`)
 const star=p.locator('.task-star').first()
 assert.equal((await star.innerText()).trim(),'','task shortcut is icon-only')
 await star.click()
 assert.ok((await p.getByRole('textbox',{name:'Ask Magic'}).inputValue()).length>0)
 assert.equal(await p.locator('[data-server-action]').count(),0,'task shortcut asks before executing')
 await p.getByRole('tab',{name:'nearby & events'}).click()
 await p.getByLabel('City or neighborhood',{exact:true}).fill('San Francisco')
 await p.getByRole('button',{name:'find city',exact:true}).click()
 await p.getByRole('button',{name:'San Francisco, United States',exact:true}).click()
 await p.getByRole('button',{name:'find places for me',exact:true}).click()
 await p.getByRole('heading',{name:'✶ Fixture Coffee',exact:true}).waitFor()
 await p.getByRole('button',{name:/^save to /}).click()
 assert.ok(await p.evaluate(()=>JSON.parse(localStorage.getItem('tatada:v1:preview')).items.some(i=>i.text==='Check out Fixture Coffee')))
 await p.screenshot({path:'scripts/out/discover-nearby.png',fullPage:true})
 await p.getByRole('button',{name:'events',exact:true}).click()
 assert.equal(await p.getByRole('link',{name:'Partiful ↗',exact:true}).count(),1)
 assert.ok((await p.getByRole('link',{name:'Luma ↗',exact:true}).getAttribute('href')).includes('San%20Francisco'))
 await p.getByRole('button',{name:'Close Magic'}).click()
 await p.goto(`${base}/#/trips`)
 await p.getByRole('button',{name:'my map & timeline',exact:true}).click()
 assert.match(await p.locator('.travel-stats').innerText(),/0\s*countries/)
 await p.getByLabel('Travel photos',{exact:true}).setInputFiles('public/wardrobe/white-sweater.png')
 await p.getByLabel('Photo city',{exact:true}).waitFor()
 await p.getByLabel('Photo city',{exact:true}).fill('Lisbon')
 await p.getByLabel('Photo country',{exact:true}).fill('Portugal')
 await p.getByLabel('Date for white-sweater.png',{exact:true}).fill('2024-02-08')
 await p.getByRole('button',{name:'add to my timeline',exact:true}).click()
 await p.getByRole('button',{name:'open trip',exact:true}).waitFor()
 assert.match(await p.locator('.travel-stats').innerText(),/1\s*countries/)
 assert.match(await p.locator('.travel-stats').innerText(),/0\s*photo stops/)
 await p.reload()
 await p.getByRole('button',{name:'my map & timeline',exact:true}).click()
 await p.locator('.photo-timeline li').first().waitFor()
 assert.equal(await p.locator('.photo-timeline li').count(),1)
 await p.getByLabel('Travel photos',{exact:true}).setInputFiles('public/wardrobe/white-sweater.png')
 await p.getByText('These photos are already in your timeline.',{exact:true}).waitFor()
 await p.screenshot({path:'scripts/out/travel-timeline.png',fullPage:true})
 await p.getByRole('button',{name:'open trip',exact:true}).click()
 await p.locator('.trip-photo-timeline img').waitFor()
 assert.deepEqual(errors,[])
 console.log('Passed: task star review, nearby search/save, provider links, photo timeline, no invented GPS/stats, deduplication, reload, trip journal.')
}finally{await browser.close()}
